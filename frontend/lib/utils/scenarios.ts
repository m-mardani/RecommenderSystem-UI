/** Returns the config for a given scenario type, or undefined. */
export const getScenarioConfig = (type: ScenarioType | string | null | undefined): ScenarioConfig | undefined => {
  if (!type) return undefined;
  return SCENARIO_CONFIGS[type as ScenarioType];
};

/** Returns a human-readable Persian label for a scenario. Falls back to the raw type. */
export const getScenarioLabelFa = (type: ScenarioType | string | null | undefined): string => {
  const cfg = getScenarioConfig(type);
  return cfg ? cfg.labelFa : String(type ?? '–');
};

/** Returns the icon emoji for a scenario. Falls back to '⚙️'. */
export const getScenarioIcon = (type: ScenarioType | string | null | undefined): string => {
  const cfg = getScenarioConfig(type);
  return cfg ? cfg.icon : '⚙️';
};
